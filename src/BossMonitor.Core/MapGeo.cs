    private static (double x, double y) IdwCorrection(LocatorCfg cfg, double gx, double gz)
    {
        if (cfg.Corrections.Length == 0) return (0, 0);
        double totalW = 0, sumX = 0, sumY = 0;
        foreach (var p in cfg.Corrections)
        {
            double dist = Math.Sqrt((gx - p.X) * (gx - p.X) + (gz - p.Z) * (gz - p.Z));
            if (dist < 0.05) return (p.Dx, p.Dy);
            if (cfg.CorrectionRadius > 0 && dist > cfg.CorrectionRadius) continue;
            double w = 1.0 / Math.Pow(Math.Max(dist, 0.05), cfg.CorrectionPower);
            totalW += w; sumX += p.Dx * w; sumY += p.Dy * w;
        }
        return totalW > 0 ? (sumX / totalW, sumY / totalW) : (0, 0);
    }

    public static bool TryWorldToSvg(string map, double wx, double wy, double wz, out double sx, out double sy)
    {
        sx = sy = 0;
        string key = Catalog.CanonicalMapId(map);
        if (!Locators.TryGetValue(key, out var cfg)) return false;
        // EFT world: Y is height, we only project X/Z to SVG
        var (cx, cy) = IdwCorrection(cfg, wx, wz);
        sx = cfg.OriginX + wx * cfg.AX + wz * cfg.AZ + cx;
        sy = cfg.OriginY + wx * cfg.BX + wz * cfg.BZ + cy;
        return true;
    }

    /// <summary>
    /// Parse "x, y, z" position string, project to map SVG, and return the nearest Chinese POI name.
    /// Returns empty string if the map is unknown or no nearby POI exists.
    /// </summary>
    public static string DescribeLocation(string map, string position)
    {
        if (string.IsNullOrWhiteSpace(position)) return "";
        var parts = position.Split(',');
        if (parts.Length < 3 ||
            !double.TryParse(parts[0].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out double wx) ||
            !double.TryParse(parts[1].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out double wy) ||
            !double.TryParse(parts[2].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out double wz))
            return "";

        if (!TryWorldToSvg(map, wx, wy, wz, out double sx, out double sy)) return "";

        string key = Catalog.CanonicalMapId(map);
        if (!Pois.TryGetValue(key, out var pois) || pois.Length == 0) return "";

        if (!Locators.TryGetValue(key, out var cfg)) return "";
        double thresholdPx = 80 * cfg.PxPerMeter; // 80 meters threshold

        Poi? nearest = null;
        double best = double.MaxValue;
        foreach (var p in pois)
        {
            double d = Math.Sqrt((sx - p.X) * (sx - p.X) + (sy - p.Y) * (sy - p.Y));
            if (d < best) { best = d; nearest = p; }
        }

        return nearest != null && best <= thresholdPx ? nearest.Title : "";
    }
